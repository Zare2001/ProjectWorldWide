HOUR = 3600.0
PLANNER_MD = ROOT / "PLANNER.md"
MID_RUN = DarlState(num_blocks=2692, committed=1870, leased=0, unassigned=822,
                    source="http://145.38.206.143:29510", observed=True)


def site_input(name: str, partition: str, gpus: int, tput: float, batch: int,
               wait_h: float, *, used_ratio: float | None = None) -> SiteInput:
    args = f"-p {partition} -N 1 --gpus-per-node {gpus} -t 8:00:00"
    shape = Shape(f"{name}_{gpus}g_8h", parse_shape_args(name, args), args)
    wait = WaitEstimate(p50_raw_s=wait_h * HOUR, p90_raw_s=wait_h * HOUR,
                        p50_eff_s=wait_h * HOUR, p90_eff_s=wait_h * HOUR,
                        samples=3, probe_age_s=60.0, used_ratio=used_ratio)
    return SiteInput(site=name, shapes=(shape,), waits={shape.name: wait},
                     geometries={gpus: Geometry(name, gpus, tput, batch)},
                     startup_s=300.0)


SITES = (site_input("snellius", "gpu_h100", 4, 89.8, 32, 0.0),
         site_input("lumi", "standard-g", 8, 38.2, 64, 2.0))
# One search, reused: the bar checks replace the timeline wholesale, so what this plan
# selected does not matter -- only that it is a real Plan with a real PlanConfig on it.
BASE = make_plan(PlannerInputs(sites=SITES, calibration=CAL, darl=MID_RUN),
                 PlanConfig(horizon_s=24 * HOUR, num_rounds=1_000_000, lanes_max=1,
                            assume_overhead=True))
COLLECTED = Collected(inputs=PlannerInputs(sites=SITES, calibration=CAL, darl=MID_RUN),
                      provenance=(), notes=(), raw={})


def link(site: str, lane: str, submit_h: float, arrival_h: float, productive_h: float,
         end_h: float) -> Link:
    return Link(lane_id=lane, site=site, index=0, submit_s=submit_h * HOUR,
                arrival_s=arrival_h * HOUR, productive_s=productive_h * HOUR,
                end_s=end_h * HOUR, cold=True, walltime_s=(end_h - arrival_h) * HOUR)


def bars(links, *, run_end_h: float, horizon_h: float, width: int) -> list[str]:
    plan = dataclasses.replace(
        BASE,
        config=dataclasses.replace(BASE.config, horizon_s=horizon_h * HOUR),
        timeline=dataclasses.replace(BASE.timeline, links=tuple(links),
                                     run_end_s=run_end_h * HOUR))
    return report_mod.presence_bars(plan, width=width)


def rows_of(lines) -> dict[str, str]:
    return {line.split("|")[0].strip(): line.split("|")[1] for line in lines if "|" in line}


