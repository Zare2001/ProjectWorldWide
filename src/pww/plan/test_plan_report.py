"""The report: the presence bar, section 8's prose, and the worked example in PLANNER.md.

    python3 tests/test_plan_report.py

report.py's own docstring says the module exists for the ASCII presence bar -- "a table
hides co-residency ... the one quantity this planner is about is a relation between rows,
and no column shows it" -- and nothing asserted a column of it. Replacing the productive
test with `if False` left every other plan test green while the bar showed nobody
training and the federated row came out empty.

So the bar is checked COLUMN BY COLUMN against hand-computed hours here, not by asking
whether each glyph appears somewhere. The three ways it can lie are all position bugs:
drawing `#` from arrival instead of from productive (which hides c, the startup a chain
re-pays per link), drawing `#` past the run end (which hides the hours billed after the
corpus is gone), and deriving `^` from lanes rather than sites (which turns one site's
two Flower clients into a federated round that never happened).

The last four checks are about PLANNER.md rather than about code. Its worked example is
pasted output, and it drifted from the tool in the flattering direction: it quoted 18.2 M
tokens/GPU-h against the tool's 7.81 M after GPU-hours began counting the held
allocation. A doc regenerated by hand needs a test, or it is a comment.
"""

