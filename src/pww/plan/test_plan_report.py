@check("section 8 quotes the used_ratio of the shapes THIS plan chose")
def _():
    """It used to read "used_ratio on Snellius gpu_h100 is ~0.11 ... finished jobs
    consumed 11% of what they asked for" while section 1 of the same report printed
    0.1617 for that partition. The ratio is the whole argument for reading the quoted
    wait as pessimistic, and it is the input to w_eff = w*(1 - s*(1 - used_ratio)): a
    literal in the prose disagrees with the arithmetic the plan was priced with."""
    sites = (site_input("snellius", "gpu_h100", 4, 89.8, 32, 0.0, used_ratio=0.4242),
             site_input("lumi", "standard-g", 8, 38.2, 64, 2.0, used_ratio=0.3131))
    collected = Collected(
        inputs=PlannerInputs(sites=sites, calibration=CAL, darl=MID_RUN),
        provenance=(), notes=(), raw={})
    plan = make_plan(collected.inputs, BASE.config)
    text = report_mod.render(plan, collected, (), CAL)
    section8 = text[text.index("8. SBATCH"):]
    assert "0.11" not in section8 and "11%" not in section8, section8[:900]
    chosen = {o.site for o in plan.selection}
    assert chosen, plan.describe()
    for site in sites:
        ratio = next(iter(site.waits.values())).used_ratio
        assert (f"{ratio:.4f}" in section8) == (site.site in chosen), (site.site, section8)


