@check("every glyph of the presence bar lands in the column whose cost it names")
def _():
    """12 columns over a 12 h axis, so column k is sampled at k+0.5 h and every glyph is
    hand-computable. The four states are four different bills: `~` queued is free, `:` is
    allocated-but-starting-up (billed, contributing nothing -- this is c, and it is why
    chaining is not free), `#` is productive, `.` is absent."""
    rows = rows_of(bars(
        [link("snellius", "snellius-l0", 0.0, 2.0, 3.0, 10.0),
         link("lumi", "lumi-l0", 0.0, 5.0, 6.0, 12.0)],
        run_end_h=9.0, horizon_h=12.0, width=12))
    #                          hour 0123456789..
    assert rows["snellius"] == "~~:######...", rows["snellius"]
    assert rows["lumi"] == "~~~~~:###...", rows["lumi"]
    assert rows["federated"] == "      ^^^   ", repr(rows["federated"])
    assert len({len(v) for v in rows.values()}) == 1, {k: len(v) for k, v in rows.items()}
    assert set("".join(rows.values())) <= set(".~:#^ "), set("".join(rows.values()))


@check("`#` stops when the RUN ends, not when the walltime does")
def _():
    """The jobs outlive the corpus -- the client does not exit when DARL is exhausted --
    and on the live plan that is 126 of 221 GPU-h billed after there is anything left to
    train on. A bar clipped at end_s instead of run_end_s draws those hours as productive,
    which is the reading of this report that costs an allocation."""
    links = [link("snellius", "snellius-l0", 0.0, 0.0, 0.0, 12.0)]
    lines = bars(links, run_end_h=6.0, horizon_h=12.0, width=12)
    assert rows_of(lines)["snellius"] == "######......", rows_of(lines)
    assert any("the run ENDED at 6.0 h" in line for line in lines), lines
    # ... and when the run fills the axis there is nothing to warn about
    full = bars(links, run_end_h=12.0, horizon_h=12.0, width=12)
    assert rows_of(full)["snellius"] == "############", rows_of(full)
    assert not any("the run ENDED" in line for line in full), full


@check("the federated row counts SITES, not lanes")
def _():
    """Two lanes at one site are two Flower clients and the server does merge them, but
    they share the hardware, the queue, the WAN link and the failure -- that is not the
    measurement this campaign makes."""
    rows = rows_of(bars(
        [link("snellius", "snellius-l0", 0.0, 0.0, 0.0, 12.0),
         link("snellius", "snellius-l1", 0.0, 0.0, 0.0, 12.0)],
        run_end_h=12.0, horizon_h=12.0, width=12))
    assert rows["snellius"] == "############", rows["snellius"]
    assert rows["federated"].strip() == "", repr(rows["federated"])
    # a second SITE, present for exactly half the axis, does produce them
    rows = rows_of(bars(
        [link("snellius", "snellius-l0", 0.0, 0.0, 0.0, 12.0),
         link("snellius", "snellius-l1", 0.0, 0.0, 0.0, 12.0),
         link("lumi", "lumi-l0", 0.0, 6.0, 6.0, 12.0)],
        run_end_h=12.0, horizon_h=12.0, width=12))
    assert rows["federated"] == "      ^^^^^^", repr(rows["federated"])


@check("the bar reaches the reader: printed in section 3, carried in --json")
def _():
    """presence_bars() being right is worth nothing if render() stops calling it, and the
    --json consumer must get the same artifact rather than a table to re-derive it from."""
    text = report_mod.render(BASE, COLLECTED, (), CAL)
    section3 = text[text.index("3. TIMELINE"):text.index("4. PER-SITE LEDGER")]
    drawn = report_mod.presence_bars(BASE)
    assert len(rows_of(drawn)) >= 2, drawn
    for line in drawn:
        assert line in section3, line
    tree = report_mod.as_json(BASE, COLLECTED, (), CAL)
    assert tree["derived"]["presence_bars"] == drawn, tree["derived"]["presence_bars"]


